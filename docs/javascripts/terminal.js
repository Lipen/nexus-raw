/*
 * Replays a recorded nexus-raw session in the landing hero.
 *
 * The recording is made by `just demo-cast`: the real `nxr` binary against the
 * repo's mock server. This player decides nothing about the session — the cast
 * carries the lines, their colors (`kinds`) and their pace (`at`), all written
 * by `examples/demo/stage.py`. The SVG in the markup is drawn from the same
 * three fields, so the still, the animation and the player are one story, and
 * this file only draws it.
 *
 * Nothing here invents output.
 */
(() => {
  const frameSelector = ".nxr-term[data-cast]";

  const frames = [...document.querySelectorAll(frameSelector)];
  if (!frames.length) return;

  const reducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)");

  for (const frame of frames) {
    const source = new URL(frame.dataset.cast, document.baseURI).href;
    load(source).then(
      (cast) => mount(frame, cast),
      () => {
        /* No cast: the SVG already in the markup stays, and it animates itself. */
      },
    );
  }

  async function load(url) {
    // Revalidate instead of `force-cache`: the recording is regenerated by
    // `just demo-cast`, and a stale copy would outlive the deploy that fixed it.
    const response = await fetch(url, { cache: "no-cache" });
    if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
    const cast = await response.json();
    const { lines, at, kinds } = cast;
    if (!Array.isArray(lines) || !lines.length) throw new Error(`${url}: no lines`);
    if (!lines.every((line) => Array.isArray(line) && typeof line[1] === "string")) {
      throw new Error(`${url}: malformed lines`);
    }
    // A cast without a timeline or colors is a cast this player cannot pace or
    // paint; the SVG fallback is the honest answer, not a guessed pace.
    if (!Array.isArray(at) || at.length !== lines.length) throw new Error(`${url}: no timeline`);
    if (!Array.isArray(kinds) || kinds.length !== lines.length) {
      throw new Error(`${url}: no line kinds`);
    }
    return cast;
  }

  function mount(frame, cast) {
    const lines = cast.lines;
    const at = cast.at.map(Number);

    const bar = document.createElement("div");
    bar.className = "nxr-term__bar";
    const dots = document.createElement("span");
    dots.className = "nxr-term__dots";
    dots.setAttribute("aria-hidden", "true");
    const title = document.createElement("span");
    title.className = "nxr-term__title";
    title.textContent = cast.title;
    const replay = document.createElement("button");
    replay.className = "nxr-term__replay";
    replay.type = "button";
    replay.textContent = "replay";
    replay.hidden = true;
    bar.append(dots, title, replay);

    const body = document.createElement("div");
    body.className = "nxr-term__body";

    const nodes = lines.map(([, text], index) => {
      const node = document.createElement("div");
      const kind = cast.kinds[index];
      node.className = kind ? `nxr-l nxr-l--${kind}` : "nxr-l";
      node.textContent = text;
      node.hidden = true;
      body.append(node);
      return node;
    });
    const texts = lines.map(([, text]) => text);

    const cursor = document.createElement("div");
    cursor.className = "nxr-l nxr-term__cursor";
    body.append(cursor);

    frame.replaceChildren(bar, body);
    frame.dataset.ready = "true";

    if (reducedMotion.matches) {
      // No animation: the whole transcript, shown at its end.
      for (const node of nodes) node.hidden = false;
      cursor.hidden = true;
      body.scrollTop = body.scrollHeight;
      return;
    }

    let shown = 0;
    let startedAt = 0;
    let raf = 0;
    let generation = 0;

    /* A command types itself out; the machine's output just prints. The window
     * is the one the SVG draws: most of the gap to the next line, ~9 ms a
     * character. `generation` retires typers from a previous replay. */
    const typeCommand = (node, text, gapMs) => {
      const gen = generation;
      const ms = Math.min(Math.max(text.length * 9, 350), 1100, gapMs * 0.7);
      const t0 = performance.now();
      const step = (now) => {
        if (gen !== generation) return;
        const n = Math.min(text.length, 1 + Math.floor(((now - t0) / ms) * text.length));
        node.textContent = text.slice(0, n);
        if (n < text.length) requestAnimationFrame(step);
      };
      requestAnimationFrame(step);
    };

    const reveal = (now) => {
      const elapsed = now - startedAt;
      let added = false;
      while (shown < nodes.length && at[shown] <= elapsed) {
        const node = nodes[shown];
        node.hidden = false;
        if (cast.kinds[shown] === "cmd") {
          const gap = (shown + 1 < at.length ? at[shown + 1] : cast.cycle ?? at[shown] + 2500) - at[shown];
          typeCommand(node, cast.lines[shown][1], gap);
        }
        shown += 1;
        added = true;
      }
      // The window keeps a fixed height: follow the tail like a real terminal.
      if (added) body.scrollTop = body.scrollHeight;
      if (shown >= nodes.length) {
        cursor.hidden = true;
        replay.hidden = false;
        raf = 0;
        return;
      }
      raf = requestAnimationFrame(reveal);
    };

    const play = () => {
      cancelAnimationFrame(raf);
      generation += 1;
      for (const [index, node] of nodes.entries()) {
        node.hidden = true;
        node.textContent = texts[index];
      }
      cursor.hidden = false;
      replay.hidden = true;
      shown = 0;
      startedAt = performance.now();
      raf = requestAnimationFrame(reveal);
    };

    replay.addEventListener("click", () => {
      play();
      frame.scrollIntoView({ block: "nearest", behavior: "smooth" });
    });

    // Play once, when the terminal is actually on screen; a session that runs
    // off screen is a session nobody sees.
    if ("IntersectionObserver" in window) {
      const observer = new IntersectionObserver(
        (entries) => {
          for (const entry of entries) {
            if (entry.isIntersecting && !shown && !raf) play();
          }
        },
        { threshold: 0.35 },
      );
      observer.observe(frame);
    } else {
      play();
    }
  }
})();
